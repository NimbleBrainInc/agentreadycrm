"""Golden: the UI surface a host reads off this server, on the wire.

A host learns the app from three places: the ``ui://`` resources it lists and reads, the
``_meta`` on each tool (where a tool names the view a host renders for it), and the ``_meta``
on each record template (where ``ai.nimblebrain/view`` names the view that shows a record).
``golden/ui_surface.json`` freezes all three as a client receives them, with the SHA-256 of
each view's HTML for the fixed bundle in ``golden/ui_bundle``.

The surface is taken in a child process, because the only contract for where the bundle
lives is ``$PEOPLE_UI_DIR`` at the server's start (here on the local runtime). The test depends
on nothing else about how the server loads or declares its UI, so it holds across a change to
either.

The golden file is frozen output, not generated by the test. A failure means a host would
see a different app: list each difference and why it is intended before editing the file.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

GOLDEN_DIR = Path(__file__).parent / "golden"
GOLDEN = GOLDEN_DIR / "ui_surface.json"
BUNDLE = GOLDEN_DIR / "ui_bundle"

#: Both protocol eras: a host on either reads the same app.
MODES = ("auto", "legacy")

# Runs in the child: connects a client in the era named by argv[1] and prints the surface.
_TAKE_SURFACE = """
import asyncio, hashlib, json, sys

from fastmcp import Client

from mcp_people.server import mcp

VIEW_META = "ai.nimblebrain/view"


def wire(model):
    return model.model_dump(mode="json", by_alias=True, exclude_none=True)


async def main(mode):
    async with Client(mcp, mode=mode) as client:
        resources = []
        for resource in await client.list_resources():
            listed = wire(resource)
            if not listed["uri"].startswith("ui://"):
                continue
            [content] = await client.read_resource(listed["uri"])
            read = wire(content)
            read["sha256"] = hashlib.sha256(read.pop("text").encode("utf-8")).hexdigest()
            resources.append({"listed": listed, "read": read})
        templates = [wire(t) for t in await client.list_resource_templates()]
        tools = [wire(t) for t in await client.list_tools()]
    return {
        "ui_resources": sorted(resources, key=lambda r: r["listed"]["uri"]),
        "ui_resource_templates": sorted(
            (t for t in templates if t["uriTemplate"].startswith("ui://")),
            key=lambda t: t["uriTemplate"],
        ),
        "tool_meta": {t["name"]: t.get("_meta") for t in sorted(tools, key=lambda t: t["name"])},
        "record_views": {
            t["uriTemplate"]: (t.get("_meta") or {}).get(VIEW_META)
            for t in sorted(templates, key=lambda t: t["uriTemplate"])
            if not t["uriTemplate"].startswith("ui://")
        },
    }


sys.stdout.write("SURFACE " + json.dumps(asyncio.run(main(sys.argv[1]))) + "\\n")
"""


def take_surface(mode: str, db: Path) -> dict:
    """The UI surface a client in ``mode`` receives from a server started on the fixed bundle."""
    env = {k: v for k, v in os.environ.items() if not k.startswith("PEOPLE_")}
    out = subprocess.run(
        [sys.executable, "-c", _TAKE_SURFACE, mode],
        env={
            **env,
            "PEOPLE_UI_DIR": str(BUNDLE),
            "PEOPLE_RUNTIME": "local",
            "PEOPLE_LOCAL_DB": str(db),
        },
        capture_output=True,
        text=True,
        check=True,
        timeout=120,
    ).stdout
    [line] = [ln for ln in out.splitlines() if ln.startswith("SURFACE ")]
    return json.loads(line.removeprefix("SURFACE "))


@pytest.mark.parametrize("mode", MODES)
def test_the_ui_surface_matches_the_golden_file(mode: str, tmp_path: Path):
    assert take_surface(mode, tmp_path / "crm.db") == json.loads(GOLDEN.read_text(encoding="utf-8"))


def test_the_golden_surface_is_the_four_views_of_one_bundle():
    """What the frozen file says, stated: four views, each the bundle with its view named on
    the root element, so the four hashes differ; no tool names a view; and no record template
    names one, so a host opens a record in the app's first view."""
    golden = json.loads(GOLDEN.read_text(encoding="utf-8"))
    assert [r["listed"]["uri"] for r in golden["ui_resources"]] == [
        "ui://people/contacts",
        "ui://people/opportunities",
        "ui://people/organizations",
        "ui://people/settings",
    ]
    assert {r["listed"]["mimeType"] for r in golden["ui_resources"]} == {
        "text/html;profile=mcp-app"
    }
    assert {r["read"]["mimeType"] for r in golden["ui_resources"]} == {"text/html;profile=mcp-app"}
    assert len({r["read"]["sha256"] for r in golden["ui_resources"]}) == 4
    assert golden["ui_resource_templates"] == []
    assert not any("ui" in (meta or {}) for meta in golden["tool_meta"].values())
    assert set(golden["record_views"].values()) == {None}
